def load_mnist():
    """Load MNIST train and test sets."""
    transform = transforms.Compose([
        transforms.ToTensor(),
        transforms.Normalize((0.1307,), (0.3081,))  # MNIST mean & std
    ])
    train_set = datasets.MNIST(DATA_DIR, train=True, download=True, transform=transform)
    test_set = datasets.MNIST(DATA_DIR, train=False, download=True, transform=transform)
    train_loader = DataLoader(train_set, batch_size=BATCH_SIZE, shuffle=True)
    test_loader = DataLoader(test_set, batch_size=BATCH_SIZE, shuffle=False)
    return train_loader, test_loader


# ----------------------------------------------------------------------------
# 3. Training
# ----------------------------------------------------------------------------
def train_model(model, train_loader, epochs=EPOCHS):
    """Standard (non-Bayesian) training with cross-entropy.  The Bayesian part
    comes at *inference* time, not training time -- the dropout layers present
    during training are the variational family."""
    optimizer = optim.Adam(model.parameters(), lr=LR)
    criterion = nn.CrossEntropyLoss()
    train_losses = []
    train_accs = []

    for epoch in range(epochs):
        model.train()
        running_loss = 0.0
        correct = 0
        total = 0
        for batch_idx, (data, target) in enumerate(train_loader):
            optimizer.zero_grad()
            output = model(data)
            loss = criterion(output, target)
            loss.backward()
            optimizer.step()
            running_loss += loss.item()
            pred = output.argmax(dim=1)
            correct += pred.eq(target).sum().item()
            total += target.size(0)

        epoch_loss = running_loss / len(train_loader)
        epoch_acc = correct / total
        train_losses.append(epoch_loss)
        train_accs.append(epoch_acc)
        print(f"  Epoch {epoch+1}/{epochs}  loss={epoch_loss:.4f}  acc={epoch_acc:.4f}")

    return train_losses, train_accs


# ----------------------------------------------------------------------------
# 4. Monte Carlo Dropout Inference
# ----------------------------------------------------------------------------
def mc_dropout_predict(model, x, num_samples=NUM_MC_SAMPLES):
    """
    Run T stochastic forward passes (dropout stays ON) and return:
      - mean_probs     : averaged softmax probabilities [N, 10]
      - predictive_entropy : H[p(y|x)]  -- total uncertainty      [N]
      - mutual_information : H[p(y|x)] - E_q[H[p(y|x,theta)]]   [N]
                             (epistemic / model uncertainty)
    """
    # KEEP model in train mode so dropout is active!
    model.train()
    all_probs = []
    with torch.no_grad():
        for _ in range(num_samples):
            logits = model(x)
            probs = F.softmax(logits, dim=1)
            all_probs.append(probs)
    all_probs = torch.stack(all_probs)  # [T, N, 10]

    # Predictive distribution: average over T samples
    mean_probs = all_probs.mean(dim=0)  # [N, 10]

    # Predictive entropy: H[p(y|x)] = -sum_c p_bar(c|x) log p_bar(c|x)
    eps = 1e-10
    predictive_entropy = -(mean_probs * torch.log(mean_probs + eps)).sum(dim=1)

    # Expected entropy (aleatoric): (1/T) sum_t H[p(y|x,theta_t)]
    sample_entropies = -(all_probs * torch.log(all_probs + eps)).sum(dim=2)  # [T, N]
    expected_entropy = sample_entropies.mean(dim=0)  # [N]

    # Mutual information = predictive_entropy - expected_entropy  (epistemic)
    mutual_information = predictive_entropy - expected_entropy

    return mean_probs, predictive_entropy, mutual_information


# ----------------------------------------------------------------------------
# 5. Evaluation & Visualization
# ----------------------------------------------------------------------------
def evaluate_model(model, test_loader, num_mc_samples=NUM_MC_SAMPLES):
    """Full evaluation on the test set."""
    all_mean_probs = []
    all_pe = []
    all_mi = []
    all_preds = []
    all_targets = []

    for data, target in test_loader:
        mean_probs, pe, mi = mc_dropout_predict(model, data, num_mc_samples)
        all_mean_probs.append(mean_probs)
        all_pe.append(pe)
        all_mi.append(mi)
        all_preds.append(mean_probs.argmax(dim=1))
        all_targets.append(target)

    all_mean_probs = torch.cat(all_mean_probs)
    all_pe = torch.cat(all_pe)
    all_mi = torch.cat(all_mi)
    all_preds = torch.cat(all_preds)
    all_targets = torch.cat(all_targets)

    correct = (all_preds == all_targets).numpy()
    accuracy = correct.mean()

    return {
        "accuracy": accuracy,
        "predictions": all_preds.numpy(),
        "targets": all_targets.numpy(),
        "predictive_entropy": all_pe.numpy(),
        "mutual_information": all_mi.numpy(),
        "mean_probs": all_mean_probs.numpy(),
        "correct_mask": correct,
    }


def accuracy_vs_mc_samples(model, test_loader, sample_counts):
    """Measure accuracy as a function of the number of MC samples T."""
    accs = []
    for T in sample_counts:
        results = evaluate_model(model, test_loader, num_mc_samples=T)
        accs.append(results["accuracy"])
        print(f"  T={T:>3d}  accuracy={results['accuracy']:.4f}")
    return accs


