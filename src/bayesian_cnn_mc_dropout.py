# 1. Bayesian CNN Model
# ----------------------------------------------------------------------------
class BayesianCNN(nn.Module):
    """
    A convolutional neural network with dropout layers that are kept ACTIVE
    during inference.  Per Gal & Ghahramani (2016), applying dropout at both
    training and test time makes each stochastic forward pass equivalent to
    drawing a sample from the approximate posterior over the network weights,
    turning the network into a Monte Carlo approximation of a Bayesian
    neural network / deep Gaussian process.

    Architecture:
        Conv(1->32, 3x3) -> ReLU -> MaxPool(2x2)     -> 13x13x32
        Conv(32->64, 3x3) -> ReLU -> MaxPool(2x2)    -> 5x5x64
        Flatten(1600) -> Dropout(0.5) -> FC(1600->128) -> ReLU
        Dropout(0.5) -> FC(128->10)
    """

    def __init__(self, dropout_rate=DROPOUT_RATE):
        super().__init__()
        self.conv1 = nn.Conv2d(1, 32, kernel_size=3, stride=1)
        self.conv2 = nn.Conv2d(32, 64, kernel_size=3, stride=1)
        self.fc1 = nn.Linear(1600, 128)  # 64 channels * 5 * 5 after conv+pool
        self.fc2 = nn.Linear(128, 10)
        # Dropout is the core of the Bayesian approximation.
        # It is NOT turned off at test time -- that is the whole point.
        self.dropout = nn.Dropout(p=dropout_rate)

    def forward(self, x):
        x = F.relu(self.conv1(x))
        x = F.max_pool2d(x, 2)
        x = F.relu(self.conv2(x))
        x = F.max_pool2d(x, 2)
        x = torch.flatten(x, 1)
        x = self.dropout(x)
        x = F.relu(self.fc1(x))
        x = self.dropout(x)
        x = self.fc2(x)
        return x  # raw logits; softmax applied outside


